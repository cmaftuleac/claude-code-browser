import React, { useEffect, useState } from 'react';
import ReactMarkdown, { type Components } from 'react-markdown';
import type { PluggableList } from 'unified';
import remarkGfm from 'remark-gfm';
import remarkMath from 'remark-math';
import remarkEmoji from 'remark-emoji';
import rehypeRaw from 'rehype-raw';
import rehypeSanitize, { defaultSchema } from 'rehype-sanitize';
import rehypeKatex from 'rehype-katex';
import rehypeHighlight from 'rehype-highlight';
import rehypeSlug from 'rehype-slug';
import rehypeAutolinkHeadings from 'rehype-autolink-headings';

import 'katex/dist/katex.min.css';
import 'katex/contrib/mhchem'; // enables \ce{...} chemical equations inside KaTeX
import 'highlight.js/styles/github-dark.css';

/**
 * Sanitize schema for raw HTML (rehype-raw). Built on the GitHub default and
 * widened to render media tags (video/audio/source/track) and to keep the
 * `math-inline`/`math-display` marker classes remark-math emits so rehype-katex
 * can transform them after sanitizing. KaTeX/highlight.js output is generated by
 * plugins that run AFTER sanitize, so it is trusted and never hits this list.
 * `<iframe>` is intentionally excluded (embed/exfil vector).
 */
const schema = {
  ...defaultSchema,
  tagNames: [...(defaultSchema.tagNames ?? []), 'video', 'audio', 'source', 'track'],
  attributes: {
    ...defaultSchema.attributes,
    span: [...(defaultSchema.attributes?.span ?? []), ['className', 'math', 'math-inline']],
    div: [...(defaultSchema.attributes?.div ?? []), ['className', 'math', 'math-display']],
    code: [...(defaultSchema.attributes?.code ?? []), ['className', /^language-./]],
    video: ['src', 'controls', 'width', 'height', 'poster', 'preload', 'loop', 'muted', 'autoPlay', 'playsInline'],
    audio: ['src', 'controls', 'preload', 'loop', 'muted', 'autoPlay'],
    source: ['src', 'type', 'srcSet', 'media', 'sizes'],
    track: ['src', 'kind', 'srcLang', 'label', 'default'],
  },
};

const remarkPlugins: PluggableList = [remarkGfm, remarkMath, remarkEmoji];

const rehypePlugins: PluggableList = [
  rehypeRaw,
  [rehypeSanitize, schema],
  rehypeKatex,
  [rehypeHighlight, { plainText: ['mermaid'] }],
  rehypeSlug,
  [rehypeAutolinkHeadings, { behavior: 'wrap' }],
];

function hastText(node: unknown): string {
  const n = node as { type?: string; value?: string; children?: unknown[] };
  if (!n) return '';
  if (n.type === 'text') return n.value ?? '';
  if (Array.isArray(n.children)) return n.children.map(hastText).join('');
  return '';
}

// Lazy-load Mermaid (~hundreds of KB) only when a diagram is actually rendered,
// keeping it out of the initial side-panel bundle.
let mermaidSeq = 0;
let mermaidLoader: Promise<typeof import('mermaid').default> | null = null;
function loadMermaid() {
  if (!mermaidLoader) {
    mermaidLoader = import('mermaid').then(({ default: mermaid }) => {
      mermaid.initialize({ startOnLoad: false, securityLevel: 'strict', theme: 'dark' });
      return mermaid;
    });
  }
  return mermaidLoader;
}

function Mermaid({ code }: { code: string }) {
  const [svg, setSvg] = useState('');
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    let alive = true;
    const id = `mmd-${mermaidSeq++}`;
    loadMermaid()
      .then((mermaid) => mermaid.render(id, code.trim()))
      .then(({ svg }) => { if (alive) { setSvg(svg); setError(null); } })
      .catch((e: unknown) => { if (alive) setError(e instanceof Error ? e.message : String(e)); });
    return () => { alive = false; };
  }, [code]);

  if (error) return <pre className="md-mermaid md-mermaid--error" title={error}>{code}</pre>;
  // fade handled by CSS (.md-mermaid) once content lands
  return <div className="md-mermaid" data-ready={svg ? 'true' : 'false'} dangerouslySetInnerHTML={{ __html: svg }} />;
}

function classList(node: { properties?: { className?: unknown } } | undefined): string[] {
  const c = node?.properties?.className;
  if (Array.isArray(c)) return c.map(String);
  if (typeof c === 'string') return c.split(/\s+/);
  return [];
}

const components: Components = {
  a({ href, children, ...rest }) {
    // In-page anchors (heading links) stay in-page; external links open in a new
    // browser tab via the extension API rather than navigating the side panel.
    if (href?.startsWith('#')) {
      return <a href={href} {...rest}>{children}</a>;
    }
    return (
      <a
        href={href}
        target="_blank"
        rel="noopener noreferrer"
        onClick={(e) => { e.preventDefault(); if (href) chrome.tabs.create({ url: href }); }}
        {...rest}
      >
        {children}
      </a>
    );
  },
  pre(props) {
    const { node, children } = props as {
      node?: { children?: Array<{ tagName?: string; properties?: { className?: unknown } }> };
      children?: React.ReactNode;
    };
    const codeEl = node?.children?.find((c) => c.tagName === 'code');
    if (codeEl && classList(codeEl).includes('language-mermaid')) {
      return <Mermaid code={hastText(codeEl)} />;
    }
    return <pre>{children}</pre>;
  },
};

export function Markdown({ children }: { children: string }) {
  return (
    <ReactMarkdown remarkPlugins={remarkPlugins} rehypePlugins={rehypePlugins} components={components}>
      {children}
    </ReactMarkdown>
  );
}
